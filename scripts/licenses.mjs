#!/usr/bin/env node
/**
 * Prints docs/security/dependencies.md: every package that ships inside the app, with its version
 * and licence, read from the installed packages. Run `npm run licenses` after changing dependencies.
 *
 * What ships: the runtime dependencies (and theirs), bundled into the main process by electron-vite;
 * React and React DOM, bundled into the window; and Electron itself. Build and test tools
 * (devDependencies other than those) never reach the app.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const tree = JSON.parse(execFileSync('npm', ['ls', '--omit=dev', '--all', '--json'], { encoding: 'utf8' }));
const seen = new Map();
const walk = (deps = {}) => {
  for (const [name, d] of Object.entries(deps)) {
    if (!d.version || seen.has(`${name}@${d.version}`)) continue;
    seen.set(`${name}@${d.version}`, { name, version: d.version });
    walk(d.dependencies);
  }
};
walk(tree.dependencies);
// Bundled into the renderer or the app shell although they're devDependencies for the build.
for (const name of ['react', 'react-dom', 'scheduler', 'electron']) {
  try {
    const p = JSON.parse(readFileSync(join(root, 'node_modules', name, 'package.json'), 'utf8'));
    seen.set(`${name}@${p.version}`, { name, version: p.version });
  } catch { /* not installed */ }
}
const licence = ({ name }) => {
  try {
    const p = JSON.parse(readFileSync(join(root, 'node_modules', name, 'package.json'), 'utf8'));
    return typeof p.license === 'string' ? p.license : p.license?.type ?? (Array.isArray(p.licenses) ? p.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN');
  } catch { return 'UNKNOWN'; }
};
const rows = [...seen.values()].map((d) => ({ ...d, licence: licence(d) })).sort((a, b) => a.name.localeCompare(b.name));
const counts = rows.reduce((m, r) => m.set(r.licence, (m.get(r.licence) ?? 0) + 1), new Map());
console.log(`# Dependencies that ship in PM Workbench ${pkg.version}

Generated by \`npm run licenses\` (scripts/licenses.mjs) from the installed packages. Do not edit by hand.

These are the only third-party packages inside the built app:
- the runtime dependencies, bundled into the main process;
- React, bundled into the window;
- Electron, which includes Chromium and Node.js under their own licences.

Build and test tools are not shipped. **None of these packages is a telemetry, analytics, crash-reporting or update SDK.**

**Licences:** ${[...counts].map(([l, n]) => `${l} (${n})`).join(', ')}.

| Package | Version | Licence |
|---|---|---|
${rows.map((r) => `| ${r.name} | ${r.version} | ${r.licence} |`).join('\n')}

The licences of Electron, Chromium and its other bundled components ship inside the app at
\`PM Workbench.app/Contents/Resources/licenses/\`, together with this list.`);
